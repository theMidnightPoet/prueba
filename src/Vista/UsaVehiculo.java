    public String listarVehiculos(ArrayList<Vehiculo> datos){
        String res = "Los vehiculos son: \n";
        
        Vehiculo objV;
        for (int i = 0; i < datos.size(); i++) {
            objV = datos.get(i);
            res +="Placa:"+ objV.getPlaca() + "  CodigoUnico:"+ objV.getSuRegistro().getCodigo() +
                  "  Costo Base $ "+ objV.calcularCostoBase(1.5) +
                  "  Costo Total $" + objV.calcularCostoTotal() + "\n";            
        }
        
        return res;
    }

