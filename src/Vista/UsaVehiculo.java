    private void agregarVehiculoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarVehiculoActionPerformed
        String laPlaca = jTextField1.getText();
        String elConductor = jTextField2.getText();
        double elKilometraje = Double.parseDouble(jTextField3.getText());
        
        String elCodigo = jTextField4.getText();
        String laCiudad = jComboBox1.getSelectedItem().toString();
        int elAño = Integer.parseInt(jTextField5.getText());
        RegistroTecnico objRT = new RegistroTecnico(elCodigo,laCiudad,elAño);
        
        String elTipo = jComboBox3.getSelectedItem().toString();
        if (elTipo.equals("ELECTRICO")){
            double laAutonomia = Double.parseDouble(jTextField6.getText());
            int laCapacidadBateria = Integer.parseInt(jTextField7.getText());
            VehiculoElectrico objVE = new VehiculoElectrico(laAutonomia,laCapacidadBateria,laPlaca,elConductor,elKilometraje,objRT);
            losVehiculos.add(objVE);
            
        }else{
            int elCilindraje = Integer.parseInt(jTextField8.getText());
            String elCombustible = jComboBox2.getSelectedItem().toString();
            VehiculoCombustion objVC =new VehiculoCombustion(elCilindraje,elCombustible, laPlaca,elConductor,elKilometraje,objRT);
            losVehiculos.add(objVC);
        }        
    }//GEN-LAST:event_agregarVehiculoActionPerformed

    private void ejecutarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ejecutarReporteActionPerformed
        String elReporte = jComboBox4.getSelectedItem().toString();
        if (elReporte.equals("Reporte A")){
            jTextArea1.setText("En construcción");
        }else{
            jTextArea1.setText(listarVehiculos(losVehiculos));
        }  
    }//GEN-LAST:event_ejecutarReporteActionPerformed

